/* Road stamps used by MapRoute_RenderAutoPath (src/worldmap_path.c) to
 * build a road procedurally between two world map nodes, instead of
 * relying on a hand-authored gWorldmapSprite_N line for every pair of
 * connected nodes. Each blob is in the same run-length format
 * MapRoute_RenderPathGfx already understands ([x, y, numTiles, repeat]
 * runs of u16 tile entries, terminated by 0xFF).
 *
 * Straight pieces are anchored top-left at the stamp's tile position and
 * advance the walk by 1 tile: Horizontal is 1 tile wide by 2 tall (stacks
 * side by side along x), Vertical is 2 wide by 1 tall (stacks along y).
 *
 * Diagonal pieces (and their connector variants below) are a 3x3 diamond
 * of tiles -- (1,0), (0,1)/(1,1)/(2,1), (1,2) in local space -- authored
 * around a center tile, so they're anchored 1 tile up-and-left of the
 * stamp position (local (1,1) lands on the walk's current tile) and also
 * advance the walk by 1 tile diagonally. Adjacent diagonal stamps agree on
 * every tile they overlap, so they tile seamlessly.
 *
 * The 8 "connect" variants replace the plain diagonal at the single tile
 * where a diagonal run bends into a straight run: they reuse the same 3x3
 * diamond but swap the tiles facing that bend for the straight piece's own
 * tiles (and, on the leading edge, pre-place the straight piece's first
 * tile), so the seam has no visible break. Naming follows the diagonal's
 * direction of travel (NE/SW for the "/" diagonal, NW/SE for the "\"
 * diagonal) and which kind of straight run it's bending into.
 *
 * Source right-tool exports lived at C:\devkitPro\feex\WM\*.road.bin; the
 * connector exports each carried one extra trailing run recorded at the
 * absolute map tile the artist was previewing against (e.g. x=0x11,y=0x0a),
 * not part of the reusable piece -- stripped here in favor of a clean 0xFF
 * terminator right after the 3x3 diamond's own data. */

